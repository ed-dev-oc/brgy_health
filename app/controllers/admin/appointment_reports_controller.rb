class Admin::AppointmentReportsController < AdminController
  layout "pdf"

  before_action :set_announcement

  def index
    @appointments = @announcement.appointment_reports.includes(:barangay)

    respond_to do |format|
      format.html
      format.pdf do
        html = render_to_string(template: "admin/appointment_reports/index")
        pdf = Grover.new(html,
          format: "A4",
          landscape: true,
          print_background: true,
          margin: {
            top: "1cm",
            bottom: "2cm",
            left: "1cm",
            right: "1cm"
          },
          display_header_footer: true,
          header_template: '
            <div style="font-size:10px; text-align:right; width:100%; padding-right:1cm;">
              Page <span class="pageNumber"></span> of <span class="totalPages"></span>
            </div>
          ',
          footer_template: '<div style="font-size: 8px; text-align: center; width: 100%;">Confidential Health Information - Generated by Health Management System</div>'
        ).to_pdf
        send_data pdf, filename: "appointments_report_#{Date.today}.pdf",
                  type: "application/pdf", disposition: "inline"
      end
    end
  end

  private

  def set_announcement
    @announcement = Announcement.find_by_public_uid(params[:announcement_id])

    if @announcement.nil?
      redirect_to admin_announcements_path, status: :see_other, alert: "Announcement not found."
    end
  end
end
